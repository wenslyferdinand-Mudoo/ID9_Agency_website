export function getFounderProjects(lang = "en") {
  return PROJECTS.map((project) => ({
    ...project,
    summary: lang === "fr" ? project.summaryFr : project.summary,
    description: lang === "fr" ? project.descriptionFr : project.description,
    challenge: lang === "fr" ? project.challengeFr : project.challenge,
    approach: lang === "fr" ? project.approachFr : project.approach,
    strategy: lang === "fr" ? project.strategyFr : project.strategy,
    solution: lang === "fr" ? project.solutionFr : project.solution,
    outcome: lang === "fr" ? project.outcomeFr : project.outcome,
    status: lang === "fr" ? project.statusFr : project.status,
    cover_image: "",
    gallery: [],
    kpis: [],
    featured: true,
    isFounderProject: true,
  }));
}

export function getFounderProjectBySlug(slug, lang = "en") {
  return getFounderProjects(lang).find((project) => project.slug === slug) || null;
}
